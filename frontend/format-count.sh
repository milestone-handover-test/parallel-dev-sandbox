#!/usr/bin/env bash
# 使い方: この file を source してから format_count "<件数>" を呼ぶと、整えた文字列が標準出力に出る。
# 画面に件数 (例: いいねの数) を出す前に、3 桁ごとにカンマを入れた表示用の文字列に整える (issue #38)。

# 本体を ( ) で囲み、中の変数が呼んだ側に漏れないようにする
format_count() (
  s="$1"
  out=""

  # 数として足し算・割り算をせず、文字列のまま右から 3 桁ずつ切り出して、間にカンマを挟む
  while [ "${#s}" -gt 3 ]; do
    out=",${s: -3}$out"
    s="${s:0:${#s}-3}"
  done

  printf '%s\n' "$s$out"
)
