#!/usr/bin/env bash
# 使い方: この file を source してから format_ago "<経過した秒数>" を呼ぶと、整えた文字列が標準出力に出る。
# 画面に投稿の時刻を出す前に、経過した秒数を「3 分前」のような表示用の文字列に整える (issue #40)。
# 整数でない入力は「format_ago: 整数ではない」、マイナスの数は「format_ago: マイナスの数 (未来の時刻)」を
# 標準エラーに出し、どちらも標準出力に何も出さず rc 2 で終わる。とても長い経過の扱いは、まだ決めていない (issue #40 の ToDo 3)。

# 本体を ( ) で囲み、中の変数が呼んだ側に漏れないようにする
format_ago() (
  s="$1"

  # 符号と数字に分ける
  sign=""
  digits="$s"
  if [ "${s:0:1}" = "-" ]; then
    sign="-"
    digits="${s:1}"
  fi

  # 受け付けるのは「先頭に - が 0 か 1 個 + 半角の数字 1 個以上」だけ。整数かどうかを先に見るので、
  # -1.5 や -abc は「マイナスの数」でなく「整数ではない」になる。
  # [0-9] は範囲の解釈がロケールで変わりうるので、数字を 10 個並べて書く
  case "$digits" in
    "" | *[!0123456789]*)
      printf '%s\n' "format_ago: 整数ではない" >&2
      exit 2
      ;;
  esac

  # 先頭の 0 を外す ($(( )) は 0090 を 8 進数として読んで止まるため)。0 だけが並んでいた時は 0 を残す
  digits="${digits#"${digits%%[!0]*}"}"
  if [ -z "$digits" ]; then
    digits=0
  fi

  # -0 は 0 として扱う。0 より小さい数は未来の時刻なので弾く
  if [ "$sign" = "-" ] && [ "$digits" != 0 ]; then
    printf '%s\n' "format_ago: マイナスの数 (未来の時刻)" >&2
    exit 2
  fi
  s="$digits"

  # 一番大きい単位で出し、半端は切り捨てる (90 秒は 1 分前)。
  # 最後も else にせず [ で比べる: $(( )) は数でない文字列の中のコマンドを実行しうるので、
  # 上で数字だけと確かめた後も、[ が整数と認めた枝でだけ計算する
  if [ "$s" -lt 60 ]; then
    printf '%s\n' "$s 秒前"
  elif [ "$s" -lt 3600 ]; then
    printf '%s\n' "$((s / 60)) 分前"
  elif [ "$s" -lt 86400 ]; then
    printf '%s\n' "$((s / 3600)) 時間前"
  elif [ "$s" -ge 86400 ]; then
    printf '%s\n' "$((s / 86400)) 日前"
  fi
)
